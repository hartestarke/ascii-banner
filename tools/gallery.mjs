#!/usr/bin/env node
// Gallery: one small SVG per field preset, reveal preset and bundled tagline
// font, plus an index page listing them with their sizes. Output depends only
// on the registries and the configs below (buildBanner is deterministic), so a
// rerun leaves git status clean.
import { existsSync, mkdirSync, statSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import { buildBanner, ConfigError } from "../src/index.mjs";
import { FIELD_PRESETS } from "../src/fields/index.mjs";
import { REVEAL_PRESETS } from "../src/reveals/index.mjs";
import { BUNDLED_FONTS } from "../src/fonts.mjs";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const DEFAULT_OUT = join(ROOT, "docs", "gallery");
const INDEX_NAME = "README.md";

// Each gallery SVG is built with this budget, so an entry that outgrows it
// fails the run instead of quietly bloating the README.
const MAX_BYTES = 200 * 1024;

// A quarter of the template's area and a short, slow field loop (36 frames), so
// a page of these stays light on bytes and CPU. stillAt must lie inside the
// loop; the default, 7 s, does not.
const SIZE = { width: 440, height: 120 };
const FIELD = { fps: 6, loopSeconds: 6, stillAt: 3 };
// At 120 px the letter height, not the width, bounds the tagline: the default
// maxHeight (0.34) sets 6- to 8-row fonts at 4.3-5.7 px, under the build's 6 px
// legibility warning. 0.5 keeps every bundled font at 6 px or more.
const TAGLINE = { font: "ansi-shadow", maxHeight: 0.5 };
const REVEAL_TIMING = { seconds: 1.6, hold: 2.4 };
const BASE = {
  size: SIZE,
  tagline: TAGLINE,
  field: FIELD,
  reveal: { preset: "scramble", seconds: 1.2, hold: 2.8 },
  budget: { maxBytes: MAX_BYTES },
};

const FIELD_TAGLINES = ["ascii"];
const REVEAL_TAGLINES = ["hello", "world"];
const FONT_TAGLINES = ["Hello"];

const looks = `${SIZE.width} × ${SIZE.height}, field loop ${FIELD.loopSeconds} s at ${FIELD.fps} fps`;
const quoted = (lines) => lines.map((t) => `"${t}"`).join(", ");

const FAMILIES = [
  {
    key: "fields",
    prefix: "field",
    title: "Fields",
    setting: "field.preset",
    names: Object.keys(FIELD_PRESETS),
    config: (name) => ({ ...BASE, taglines: FIELD_TAGLINES, field: { ...FIELD, preset: name } }),
    intro:
      `\`field.preset\` with its default options (see [fields.md](../fields.md)). ${looks}; ` +
      `tagline ${quoted(FIELD_TAGLINES)} in \`${TAGLINE.font}\`, scramble reveal.`,
  },
  {
    key: "reveals",
    prefix: "reveal",
    title: "Reveals",
    setting: "reveal.preset",
    names: Object.keys(REVEAL_PRESETS),
    config: (name) => ({ ...BASE, taglines: REVEAL_TAGLINES, reveal: { preset: name, ...REVEAL_TIMING } }),
    intro:
      `\`reveal.preset\` with its default options (see [reveals.md](../reveals.md)). ${looks}, waves field; ` +
      `taglines ${quoted(REVEAL_TAGLINES)} in \`${TAGLINE.font}\`, ` +
      `reveal ${REVEAL_TIMING.seconds} s + hold ${REVEAL_TIMING.hold} s per line.`,
  },
  {
    key: "fonts",
    prefix: "font",
    title: "Fonts",
    setting: "tagline.font",
    names: Object.keys(BUNDLED_FONTS),
    config: (name) => ({ ...BASE, taglines: FONT_TAGLINES, tagline: { ...TAGLINE, font: name } }),
    intro:
      `\`tagline.font\` with its default layout and shadow glyphs (see [fonts.md](../fonts.md) and ` +
      `[block-fonts.md](../block-fonts.md)). ${looks}, waves field, scramble reveal; tagline ` +
      `${quoted(FONT_TAGLINES)}. Caps-only fonts (\`ansi-shadow\` and the block faces) draw it in capitals.`,
  },
];

const USAGE = `node tools/gallery.mjs [--only ${FAMILIES.map((f) => f.key).join("|")}] [--out <dir>]

Renders one ${SIZE.width}x${SIZE.height} SVG per field preset, reveal preset and bundled font
into <dir> (default docs/gallery), then rewrites <dir>/${INDEX_NAME}.`;

const fileOf = (fam, name) => `${fam.prefix}-${name}.svg`;
const thousands = (n) => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ",");

function fail(msg) {
  console.error(`gallery: ${msg}`);
  process.exit(1);
}

/**
 * One table per family listing every registry entry, sizes read from disk; an
 * entry with no SVG in outDir (after --only into a fresh --out) shows as not built.
 */
function indexPage(outDir) {
  const out = [
    "# Gallery",
    "",
    "<!-- Generated by tools/gallery.mjs; edit that, not this file. -->",
    "",
    `This page is heavy: ${FAMILIES.reduce((n, f) => n + f.names.length, 0)} animated SVGs.`,
    "",
    "Every field preset, reveal preset and bundled tagline font, rendered small. " +
      "Rebuild with `npm run gallery`. Sizes are raw bytes of these small SVGs; " +
      "[fields.md](../fields.md) and [reveals.md](../reveals.md) give full-size (880 × 240, 20 s) figures.",
  ];
  for (const fam of FAMILIES) {
    out.push("", `## ${fam.title}`, "", fam.intro, "", `| \`${fam.setting}\` | preview | bytes |`, "| --- | --- | ---: |");
    for (const name of fam.names) {
      const file = fileOf(fam, name);
      const path = join(outDir, file);
      const exists = existsSync(path);
      const cell = exists ? `<img src="${file}" width="${SIZE.width}" alt="${name} ${fam.prefix} sample">` : "not built";
      const bytes = exists ? thousands(statSync(path).size) : "";
      out.push(`| \`${name}\` | ${cell} | ${bytes} |`);
    }
  }
  return `${out.join("\n")}\n`;
}

async function main(argv) {
  let v;
  try {
    ({ values: v } = parseArgs({
      args: argv,
      options: { only: { type: "string" }, out: { type: "string" }, help: { type: "boolean", short: "h" } },
    }));
  } catch (e) {
    fail(`${e.message}\n\n${USAGE}`);
  }
  if (v.help) return void console.log(USAGE);
  const families = v.only === undefined ? FAMILIES : FAMILIES.filter((f) => f.key === v.only);
  if (!families.length) fail(`--only takes ${FAMILIES.map((f) => f.key).join(", ")}; got "${v.only}"\n\n${USAGE}`);

  const outDir = resolve(v.out ?? DEFAULT_OUT);
  mkdirSync(outDir, { recursive: true });

  const built = [];
  const warned = new Map(); // warning text -> files; the small size makes most entries share one
  for (const fam of families) {
    for (const name of fam.names) {
      const file = fileOf(fam, name);
      let res;
      try {
        res = await buildBanner(fam.config(name), { baseDir: ROOT });
      } catch (e) {
        if (e instanceof ConfigError) fail(`${file}: ${e.message}`);
        throw e;
      }
      for (const w of res.warnings) warned.set(w, [...(warned.get(w) ?? []), file]);
      writeFileSync(join(outDir, file), res.svg);
      built.push({ file, bytes: res.stats.rawBytes });
    }
  }
  writeFileSync(join(outDir, INDEX_NAME), indexPage(outDir));
  for (const [w, files] of warned) console.error(`warning: ${w}\n  in ${files.length} SVGs: ${files.join(", ")}`);

  const total = built.reduce((s, b) => s + b.bytes, 0);
  const label = `total (${built.length} SVGs)`;
  const w = Math.max(label.length, ...built.map((b) => b.file.length));
  const n = thousands(total).length;
  for (const b of built) console.log(`${b.file.padEnd(w)}  ${thousands(b.bytes).padStart(n)}`);
  console.log(`${label.padEnd(w)}  ${thousands(total)}\n\nwrote ${built.length} SVGs and ${INDEX_NAME} to ${outDir}`);
}

main(process.argv.slice(2)).catch((e) => {
  console.error(e?.stack ?? e);
  process.exit(2);
});
