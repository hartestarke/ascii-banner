// Bundled figlet fonts, the names `tagline.font` takes besides a path to any
// .flf. An entry's layout and shadowGlyphs are what a null `tagline.layout` /
// `tagline.shadowGlyphs` fall back to; `file` and `notice` (provenance and
// licence) are relative to the package root.
import { fileURLToPath } from "node:url";

/** `tagline.layout` values; figlet.mjs implements them. */
export const LAYOUTS = ["full", "fit", "smush", "header"];

/** What a null layout / shadowGlyphs means for a `tagline.font` given as a path. */
export const PATH_FONT_DEFAULTS = { layout: "header", shadowGlyphs: "" };

const ANSI_SHADOW = { notice: "fonts/ANSI-SHADOW-NOTICE.md", source: "TheDraw font converted by patorjk.com; no explicit licence" };
const FIGLET = { notice: "fonts/figlet/NOTICE.md", source: "BSD-3-Clause, official FIGlet distribution (cmatsuoka/figlet)" };
const BLOCK = { notice: "fonts/block/NOTICE.md", source: "MIT, drawn for this project; generated by tools/mkfont.mjs" };

// The FIGlet fonts draw face and shadow edges with the same ASCII strokes, so
// there is no shadow-only glyph set to dim.
const figletFont = (name) => ({ file: `fonts/figlet/${name}.flf`, shadowGlyphs: "", layout: "header", ...FIGLET });

// mkfont faces have their spacing drawn in, so they are set at full width.
const blockFont = (name, shadowGlyphs = "") => ({ file: `fonts/block/${name}.flf`, shadowGlyphs, layout: "full", ...BLOCK });

export const BUNDLED_FONTS = {
  // Full width although its header asks for fitting: the default banner is
  // tuned to it, and layout "fit" gives figlet's own spacing.
  "ansi-shadow": { file: "fonts/ansi-shadow.flf", shadowGlyphs: "═║╔╗╚╝", layout: "full", ...ANSI_SHADOW },
  standard: figletFont("standard"),
  big: figletFont("big"),
  slant: figletFont("slant"),
  small: figletFont("small"),
  shadow: figletFont("shadow"),
  block: figletFont("block"),
  lean: figletFont("lean"),
  mini: figletFont("mini"),
  script: figletFont("script"),
  banner: figletFont("banner"),
  smslant: figletFont("smslant"),
  smshadow: figletFont("smshadow"),
  smscript: figletFont("smscript"),
  blocks: blockFont("blocks"),
  "blocks-shadow": blockFont("blocks-shadow", "░"),
  "blocks-thin": blockFont("blocks-thin"),
  pixel: blockFont("pixel"),
  "blocks-3d": blockFont("blocks-3d", "▇▉"),
};

/** Absolute path of a package-relative file. */
export const packagePath = (rel) => fileURLToPath(new URL(`../${rel}`, import.meta.url));

export const isBundledFont = (name) => Object.hasOwn(BUNDLED_FONTS, name);

/** Registry entries in listing order, with the absolute .flf path. */
export const listFonts = () => Object.entries(BUNDLED_FONTS).map(([name, f]) => ({ name, ...f, path: packagePath(f.file) }));
